#Requires -Modules Logging

# Write config/lancommander.cs, which tribes-server runs with +exec. console.cs runs +exec files
# after config/Server/ServerPrefs.cs and before createServer(), so the non-empty TRIBES_* settings
# here win over ServerPrefs.cs. The file also turns on console.log, which tribes-server streams to
# docker logs.
#
# Admin passwords can't go in that file: config/Server/adminpasswords.cs runs later, during
# createServer(), and starts with admins::reset(). So TRIBES_ADMIN_PASSWORD goes into
# config/lancommanderAdmins.cs, and adminpasswords.cs gets one line that executes it.

$config = Join-Path $Env:SERVER_ROOT 'config'

if (-not (Test-Path -Path (Join-Path $Env:SERVER_ROOT 'Tribes.exe'))) {
    Write-Log -Level Error "Tribes.exe not found; skipping server configuration"
    return
}

function ConvertTo-TribesString([string] $Value) {
    '"' + $Value.Replace('\', '\\').Replace('"', '\"') + '"'
}

function Write-TribesFile([string] $Path, [string[]] $Lines) {
    [System.IO.File]::WriteAllText($Path, ($Lines -join "`r`n") + "`r`n")
    chown "$($Env:UID):$($Env:GID)" $Path
}

$settings = [ordered]@{
    'Port'            = $Env:TRIBES_PORT
    'HostName'        = $Env:TRIBES_SERVER_NAME
    'Info'            = $Env:TRIBES_SERVER_INFO
    'JoinMOTD'        = $Env:TRIBES_MOTD
    'MaxPlayers'      = $Env:TRIBES_MAX_PLAYERS
    'Password'        = $Env:TRIBES_PASSWORD
    'timeLimit'       = $Env:TRIBES_TIME_LIMIT
    'TeamDamageScale' = $Env:TRIBES_TEAM_DAMAGE
    'HostPublicGame'  = $Env:TRIBES_PUBLIC
}

$lines = @(
    '// Generated by LANCommander on every start from the TRIBES_* environment variables.'
    '// Edit config/Server/ServerPrefs.cs instead; settings with a non-empty TRIBES_* variable win.'
    ''
    '$Console::LogMode = 1;'
    ''
)

foreach ($s in $settings.GetEnumerator()) {
    if (-not $s.Value) { continue }
    $lines += "`$Server::$($s.Key) = $(ConvertTo-TribesString $s.Value);"
}

New-Item -ItemType Directory -Path $config -Force | Out-Null
Write-TribesFile -Path (Join-Path $config 'lancommander.cs') -Lines $lines
Write-Log "Wrote TRIBES_* settings to config/lancommander.cs"

# Admin login
$admins = @(
    '// Generated by LANCommander on every start from TRIBES_ADMIN_PASSWORD.'
    '// Executed from config/Server/adminpasswords.cs; add other admins there.'
)
if ($Env:TRIBES_ADMIN_PASSWORD) {
    $admins += "admin::addadmin(`"Admin`", $(ConvertTo-TribesString $Env:TRIBES_ADMIN_PASSWORD), `"Owner Admin`");"
}
Write-TribesFile -Path (Join-Path $config 'lancommanderAdmins.cs') -Lines $admins

# adminpasswords.cs is part of the 1.40/1.41 admin scripts; older versions don't have it
$serverDir = Join-Path $config 'Server'
$passwords = Get-ChildItem -Path $serverDir -File -ErrorAction SilentlyContinue |
    Where-Object { $_.Name -ieq 'adminpasswords.cs' } | Select-Object -First 1

if ($passwords) {
    if (-not (Select-String -Path $passwords.FullName -SimpleMatch 'LANCommander:' -Quiet)) {
        Add-Content -Path $passwords.FullName -Value "`r`nexec(`"lancommanderAdmins.cs`"); // LANCommander: TRIBES_ADMIN_PASSWORD`r`n" -NoNewline
        chown "$($Env:UID):$($Env:GID)" $passwords.FullName
        Write-Log "Added TRIBES_ADMIN_PASSWORD to config/Server/$($passwords.Name)"
    }
} elseif ($Env:TRIBES_ADMIN_PASSWORD) {
    Write-Log -Level Warning "config/Server/adminpasswords.cs not found; TRIBES_ADMIN_PASSWORD needs the 1.40/1.41 admin scripts and is ignored"
}
